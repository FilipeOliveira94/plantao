const levelTitle = (n) => ['Interno(a)', 'Residente R1', 'Residente R2', 'Residente R3', 'Plantonista'][n - 1] || '';

function toggleMute() {
  state.settings.muted = !state.settings.muted;
  sfx.setMuted(state.settings.muted);
  save(state);
  if (shift) renderTop(); else renderMenu();
}

