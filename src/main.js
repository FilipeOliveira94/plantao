/** Hover and focus handlers that preview an action's cut of the consultation bar. */
function previewCost(cost) {
  const set = (v) => () => {
    if ((ui.hoverCost ?? 0) === v || !shift?.current) return;
    ui.hoverCost = v;
    ui.chart.querySelector('.consult-chip')?.replaceWith(consultChip(shift.current));
  };
  return { onmouseenter: set(cost), onfocus: set(cost), onmouseleave: set(0), onblur: set(0) };
}

// the critical window counts consultation time, thinking included, like the score (P1-12)
function criticalChip(enc) {
  const tc = enc.c.timeCritical;
  return tc ? h('span', { class: `chip critical-chip${enc.minutesSpent > tc.minutes ? ' over' : ''}` }, `⏱ Janela crítica: ${Math.round((enc.minutesSpent / tc.minutes) * 100)}%`) : null;
}

/** What a clock tick can change in the chart: a full redraw when it does, else only the chips. */
const chartSig = () => JSON.stringify([shift.current?.c.id ?? null, shift.current?.readyExams(shift.clock).length, shift.over, shift.done, shift.current ? null : [firstCallable()?.c.id, firstCallable()?.status, waitButtonShown(shift.queue())]]);

function refreshChart() {
  const enc = shift.current;
  if (chartSig() !== ui.chartSig) { renderChart(); return; }
  if (!enc) return;
  ui.chart.querySelector('.consult-chip')?.replaceWith(consultChip(enc));
  const tc = criticalChip(enc);
  if (tc) ui.chart.querySelector('.critical-chip')?.replaceWith(tc);
}

