function statusOf(enc) {
  if (enc.status === 'paused') {
    const pend = enc.pendingExams(shift.clock);
    return { text: pend.length ? `⏸ Pausado · 🧪 exames até ${clockAt(Math.max(...pend.map(([, r]) => r.readyAt)))}` : '⏸ Atendimento pausado' };
  }
  if (enc.status === 'awaiting_results') {
    const pend = enc.pendingExams(shift.clock);
    if (!pend.length) return { text: '✅ Resultados prontos', ready: true };
    const t = Math.max(...pend.map(([, r]) => r.readyAt));
    return { text: `🧪 Exames até ${clockAt(t)}` };
  }
  return { text: `⏳ Chegou às ${clockAt(enc.arrivedAt)}${enc.impatient ? ' · 😤 impaciente' : ''}` };
}

const clockAt = clockLabelAt;

/** A patient in the queue can be called unless their tests are still running (paused patients always can). */
const callable = (enc) => enc.status !== 'awaiting_results' || enc.pendingExams(shift.clock).length === 0;
/** The patient "Chamar próximo" calls: the first callable one, in queue order. */
const firstCallable = (q = shift.queue()) => q.find(callable) ?? null;
const callKind = (enc) => (enc.status === 'paused' ? 'paused' : enc.status === 'awaiting_results' ? 'results' : 'waiting');

/** "Aguardar próximo" (the fast-forward) shows when the room is free and nobody can be called yet. */
function waitButtonShown(q) {
  const waitingExams = shift.encounters.some((e) => e.status === 'awaiting_results' && e.pendingExams(shift.clock).length);
  return !shift.current && !shift.over && (shift.upcoming().length || waitingExams) && !q.some((e) => statusOf(e).ready || e.status === 'waiting' || e.status === 'paused');
}

function renderQueue({ ifChanged = false } = {}) {
  const q = shift.queue();
  // a clock tick redraws the queue only when what it shows changed, so focus and hover stay put
  const showWait = waitButtonShown(q);
  const sig = JSON.stringify([q.map((e) => [e.c.id, statusOf(e).text, !shift.current && !shift.over]), shift.upcoming().length, !!shift.current, showWait]);
  if (ifChanged && sig === ui.queueSig) return;
  ui.queueSig = sig;
  const cards = q.map((enc) => {
    const tri = TRIAGE[enc.c.triage.priority];
    const st = statusOf(enc);
    const canCall = !shift.current && !shift.over && (enc.status !== 'awaiting_results' || st.ready);
    const pend = enc.pendingExams(shift.clock).map(([, r]) => r);
    const hit = jumpFresh() && ui.jump.hit.some((x) => x.enc === enc);
    return h('div', { class: `qcard ${st.ready ? 'ready' : ''}${hit ? ' hit' : ''}`, style: { borderLeftColor: tri.color } },
      h('div', { class: 'nm' }, enc.c.patient.name),
      h('div', { class: 'small muted' }, `${enc.c.patient.age} · ${tri.label}${enc.c.type === 'follow_up' ? ' · Retorno' : ''}`),
      h('div', { class: 'small' }, st.text),
      patienceMeter(enc) ?? (pend.length ? examMeter(pend) : null),
      h('button', { class: 'btn small', disabled: !canCall, onclick: () => callPatient(enc) }, 'Chamar'),
    );
  });
  const children = cards.length ? cards : [h('div', { class: 'empty' }, emptyQueueText(showWait))];
  if (showWait) {
    children.push(h('button', { class: 'btn', 'data-step': 'wait-next', style: { alignSelf: 'center' }, onclick: () => { handleEvents(timed(() => shift.waitForNext())); renderAll(); if (shift.done) setTimeout(showShiftSummary, 400); } }, '☕ Aguardar próximo'));
  }
  mount(ui.queue, children);
  pruneLive();
}

// what to do when no one is waiting (P2-01)
function emptyQueueText(showWait) {
  if (shift.done) return 'Fila vazia. Encerre o plantão para ver o resumo.';
  if (shift.current) {
    if (shift.over) return 'Fila vazia. Conclua o atendimento atual para encerrar o plantão.';
    return shift.upcoming().length ? 'Ninguém na fila agora. Siga com o atendimento; novos pacientes chegam ao longo do plantão.' : 'Fila vazia. Este é o último paciente do plantão.';
  }
  return showWait ? 'Ninguém para chamar agora. Use ☕ Aguardar próximo para adiantar o relógio.' : 'Fila vazia.';
}

function handleEvents(fired) {
  // high-impact events open a popup; cosmetic ones and waiting consequences stay as toasts
  for (const ev of fired || []) { if (ev.impact) announceEvent(ev); else toast(ev.text, 6500); }
  if (shift.over && !shift._overNotified) {
    shift._overNotified = true;
    clearArrivals(); // no one else can be called: an open arrival card has nothing left to offer
    toast(shift.current ? `⏰ ${shift.endLabel}: fim do turno. Conclua o atendimento atual; ninguém mais será chamado.` : `⏰ ${shift.endLabel}: fim do turno.`, 6500);
  }
  // newly available results for waiting patients
  for (const e of shift.encounters) {
    if ((e.status === 'awaiting_results' || e.status === 'paused') && !e._notified && e.pendingExams(shift.clock).length === 0) {
      e._notified = true; sfx.result(); toast(`Resultados de ${e.c.patient.name} disponíveis. Clique para abrir.`, 6500, { onClick: () => openResults(e) });
    }
  }
  // results ready for the patient in the room
  const cur = shift.current;
  for (const [id, r] of cur ? cur.readyExams(shift.clock) : []) {
    if (!r._notified) { r._notified = true; sfx.result(); toast(`Resultado liberado: ${EXAMS[id].label}. Clique para abrir.`, 6500, { onClick: () => openResults(cur) }); }
  }
  // an open arrival card whose patient is no longer waiting (left unseen, P1-06) has nothing to offer
  if (arrivalPopup && arrivalPopup.enc.status !== 'waiting') arrivalPopup.close();
  // new arrivals during the shift (the first patient is already waiting at the start)
  for (const e of shift.encounters) {
    if (!e._arrivalNotified && e.arrivedAt <= shift.clock) {
      e._arrivalNotified = true;
      if (e.arrivedAt > 0) announceArrival(e);
    }
  }
}

// ----------------------------------------------------------------------
// Arrival popups: one at a time, most urgent first. Red and orange block the screen with the alarm;
// the others are a compact card that goes away on its own ("Depois").
// Event popups (P1-09) share the slot: one card at a time, arrivals first.
// ----------------------------------------------------------------------
const ARRIVAL_AUTO_CLOSE_MS = 6000;
const EVENT_AUTO_CLOSE_MS = 9000;
const arrivals = [];
const events = [];
let arrivalPopup = null;
let eventPopup = null;

function clearArrivals() {
  arrivals.length = 0;
  events.length = 0;
  const p = arrivalPopup;
  const q = eventPopup;
  arrivalPopup = null;
  eventPopup = null;
  p?.close();
  q?.close();
}

/** Shows the next queued card when none is up: arrivals before events. */
function showNextNotice() {
  if (arrivalPopup || eventPopup) return;
  if (arrivals.length) showNextArrival();
  if (!arrivalPopup && events.length) showEvent(events.shift());
}

function announceArrival(enc) {
  arrivals.push(enc);
  arrivals.sort((a, b) => TRIAGE[a.c.triage.priority].order - TRIAGE[b.c.triage.priority].order);
  // a red or orange arrival does not wait behind a calm card: an arrival card counts as "Depois",
  // an event card closes (its effect stays in the top bar)
  const open = arrivalPopup ?? eventPopup;
  if (open && !open.blocking && TRIAGE[enc.c.triage.priority].order <= TRIAGE.orange.order) open.close();
  else showNextNotice();
}

function announceEvent(ev) {
  events.push(ev);
  showNextNotice();
}

function showEvent(ev) {
  if (!shift || shift.over) { events.length = 0; return; }
  const own = popup(h('div', {},
    h('span', { class: 'event-tag' }, '⚠️ Imprevisto no plantão'),
    h('p', { class: 'event-text' }, ev.text),
    ev.detail ? h('p', { class: 'event-detail small' }, ev.detail) : null,
  ), {
    className: 'event',
    timeout: EVENT_AUTO_CLOSE_MS,
    label: 'Imprevisto no plantão',
    actions: [{ label: 'Entendi', step: 'event-ok' }],
    onClose: () => { if (eventPopup === own) { eventPopup = null; showNextNotice(); } },
  });
  eventPopup = own;
}

function showNextArrival() {
  let enc;
  // skip anyone called from the queue in the meantime; after the end of the shift no one can be called
  do enc = arrivals.shift(); while (enc && enc.status !== 'waiting');
  if (!enc || !shift || shift.over) { arrivals.length = 0; return; }
  const pr = enc.c.triage.priority;
  const tri = TRIAGE[pr];
  const urgent = pr === 'red' || pr === 'orange';
  if (urgent) sfx.alarm();
  const own = popup(h('div', {},
    h('span', { class: 'arrival-tag', style: { background: tri.color, color: pr === 'yellow' ? 'var(--ink)' : null } }, `${urgent ? '🚨 ' : ''}Chegou: ${tri.label}`),
    h('div', { class: 'arrival-name' }, enc.c.patient.name, ' ', h('span', { class: 'muted small' }, `· ${enc.c.patient.age}`)),
    h('p', { class: 'arrival-complaint small' }, enc.c.triage.complaint),
  ), {
    className: `arrival${urgent ? '' : ' compact'}`,
    blocking: urgent,
    timeout: urgent ? 0 : ARRIVAL_AUTO_CLOSE_MS,
    accent: tri.color,
    label: `Novo paciente: ${enc.c.patient.name}`,
    // no static primary: the next-step highlight marks the answer and follows the room (game/nextstep.js)
    actions: [
      { label: 'Atender agora', step: 'attend', onclick: () => attendNow(enc) },
      { label: 'Depois', step: 'later' },
    ],
    onClose: () => { if (arrivalPopup === own) { arrivalPopup = null; showNextNotice(); } },
  });
  own.enc = enc;
  arrivalPopup = own;
}

/** "Atender agora": the patient in the room goes back to the queue with everything kept, and the new one comes in. */
function attendNow(enc) {
  if (!shift || shift.over || enc.status !== 'waiting') return;
  setAsideCurrent();
  callPatient(enc);
}

/** The patient in the room goes back to the queue (paused) with their chart state kept. */
function setAsideCurrent() {
  const cur = shift.current;
  if (!cur) return;
  cur._resume = { tab, decision: { ...decision } }; // chart state, restored when they are called again
  cur._notified = cur.pendingExams(shift.clock).length === 0; // toast their results if they come in meanwhile
  scene.exit();
  shift.pause();
}

/** A result toast was clicked: show that patient's Exames tab, calling them in if needed (P2-01).
 *  Someone else in the room is set aside with everything kept, like "Atender agora". */
function openResults(enc) {
  if (!shift || !shift.encounters.includes(enc) || modalOpen() || blockingPopupOpen()) return false;
  if (shift.current === enc) { sfx.page(); tab = 'tests'; renderChart(); return true; }
  if (shift.over || !['awaiting_results', 'paused'].includes(enc.status) || !callable(enc)) return false;
  setAsideCurrent();
  callPatient(enc, { openTab: 'tests' });
  return true;
}

function callPatient(enc, { openTab } = {}) {
  const returning = enc.status === 'awaiting_results';
  const resume = enc.status === 'paused' ? enc._resume : null;
  if (!shift.call(enc)) return;
  enc._resume = null;
  if (arrivalPopup?.enc === enc) arrivalPopup.close(); // called from the queue while their popup was up
  for (const [, r] of enc.readyExams(shift.clock)) r._notified = true; // shown in the chart, no toast
  enc._notified = true;
  sfx.call();
  scene.enter(enc.c.patient.look, enc.c.patient.companion);
  tab = openTab ?? resume?.tab ?? (returning ? 'tests' : 'triage');
  decision = resume?.decision ?? { dx: null, cd: null };
  testQuery = ''; openTestCats.clear(); askedOpen = false;
  ui.talk.clear();
  if (enc.c.patient.look.inBed && shift.unit.type === 'picu') sfx.alarm();
  say(enc, resume ? 'Voltei, doutor(a). Podemos continuar?' : returning ? 'Voltei, doutor(a). Os resultados saíram?' : enc.c.opening);
  renderAll();
}

// A line on the stage: the doctor's, or the patient side's (the patient or the companion, see Encounter.speaker).
function say(enc, text, who = 'pt') {
  if (who === 'doctor') { ui.talk.say('doctor', 'Você', 'doctor', text); return; }
  const sp = enc.speakerFor(text);
  ui.talk.say('pt', sp.name, sp.role, sp.text);
}

