// Builds docs/REFERENCES.md, the table of references used by each case, from src/data/cases.
// Usage: node tools/build-references.mjs          (write the file)
//        node tools/build-references.mjs --check  (fail if the file is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CASES } from '../src/data/cases/index.js';
import { SPECIALTIES } from '../src/data/catalog.js';

const OUT = fileURLToPath(new URL('../docs/REFERENCES.md', import.meta.url));
const SPECIALTY_EN = { 'internal-medicine': 'Internal medicine', pediatrics: 'Pediatrics', picu: 'Pediatric ICU' };
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

const lines = [
  '# References used by each case',
  '',
  '<!-- Generated by tools/build-references.mjs from src/data/cases. Do not edit by hand: run `npm run references`. -->',
  '',
  'The cases were generated by AI from the published guidelines and articles listed below. They are still pending physician review; see [REVIEW-STATUS.md](REVIEW-STATUS.md).',
  '',
  'The diagnosis column is in Brazilian Portuguese, as shown in the game.',
];

for (const spec of Object.keys(SPECIALTIES)) {
  const cases = CASES.filter((c) => c.specialty === spec);
  if (!cases.length) continue;
  lines.push('', `## ${SPECIALTY_EN[spec] || spec}`, '', '| Case id | Diagnosis | References |', '| --- | --- | --- |');
  for (const c of cases) {
    const dx = c.diagnosis.options.find((o) => o.id === c.diagnosis.correct)?.label || '';
    lines.push(`| \`${c.id}\` | ${cell(dx)} | ${c.references.map(cell).join('<br>')} |`);
  }
}
const text = lines.join('\n') + '\n';

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch { /* missing file counts as out of date */ }
  if (current !== text) {
    console.error('docs/REFERENCES.md is out of date. Run `npm run references` and commit the result.');
    process.exit(1);
  }
  console.log('docs/REFERENCES.md is up to date.');
} else {
  writeFileSync(OUT, text);
  console.log(`Wrote docs/REFERENCES.md (${CASES.length} cases).`);
}
